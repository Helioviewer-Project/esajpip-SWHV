{
    flag ret = TRUE;
	*pErrCode = 0;


	/*Decode lsot */
	ret = Acn_Dec_Int_PositiveInteger_ConstSize_big_endian_16(pBitStrm, (&(pVal->lsot)));
	*pErrCode = ret ? 0 : ERR_ACN_DECODE_SOTSEGMENT_LSOT;
	if (ret) {
	    /*Decode isot */
	    ret = Acn_Dec_Int_PositiveInteger_ConstSize_big_endian_16(pBitStrm, (&(pVal->isot)));
	    *pErrCode = ret ? 0 : ERR_ACN_DECODE_SOTSEGMENT_ISOT;
	    if (ret) {
	        /*Decode psot */
	        ret = Acn_Dec_Int_PositiveInteger_ConstSize_big_endian_32(pBitStrm, (&(pVal->psot)));
	        *pErrCode = ret ? 0 : ERR_ACN_DECODE_SOTSEGMENT_PSOT;
	        if (ret) {
	            /*Decode tpsot */
	            ret = Acn_Dec_Int_PositiveInteger_ConstSize_8(pBitStrm, (&(pVal->tpsot)));
	            *pErrCode = ret ? 0 : ERR_ACN_DECODE_SOTSEGMENT_TPSOT;
	            if (ret) {
	                /*Decode tnsot */
	                ret = Acn_Dec_Int_PositiveInteger_ConstSize_8(pBitStrm, (&(pVal->tnsot)));
	                *pErrCode = ret ? 0 : ERR_ACN_DECODE_SOTSEGMENT_TNSOT;
	            }   /*COVERAGE_IGNORE*/
	        }   /*COVERAGE_IGNORE*/
	    }   /*COVERAGE_IGNORE*/
	}   /*COVERAGE_IGNORE*/

    return ret && SotSegment_IsConstraintValid(pVal, pErrCode);
}


